        public void setUpCtrls()
    {
        listModel = new DefaultListModel();
        int loggedIn = AppLib.loggedOn.getUserID();
        for(int index=AppLib.postsAL.size()-1; index >= 0; index --)//int index=0; index < AppLib.postsAL.size(); index ++
        {
            Posts pObj = (Posts)AppLib.postsAL.get(index);
            int postOwnerId = pObj.getUserID();
            
            if(AppLib.friendAlready(loggedIn,postOwnerId) == true) 
            {
                listModel.addElement(pObj.getPostID());
            }
        }
        
        lstFriendsPosts.setModel(listModel);
    }


