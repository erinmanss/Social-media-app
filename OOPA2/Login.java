    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        char [] pwd = txtPwd.getPassword();
        String pwdStr = String.valueOf(pwd);
       boolean tf =  AppLib.validLogin(txtEmail.getText(), pwdStr);
       if (tf)
       {
           lblOutput.setText("Valid Log on");
           AppLib.scrMainMenu = new frmMainMenu();
           AppLib.scrMainMenu.setVisible(true);
           this.dispose();
       }
       else
       {
           countFails++;
           lblOutput.setText("Invalid Log on");
           if(countFails == 5)
           {
               JOptionPane.showMessageDialog(null, "bye bye", "night night", JOptionPane.INFORMATION_MESSAGE);
               System.exit(0);
           }
       }
    }//GEN-LAST:event_btnLoginActionPerformed

